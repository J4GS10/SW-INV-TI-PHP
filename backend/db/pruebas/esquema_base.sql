CREATE EDITIONABLE PACKAGE BODY INV_KARDEX_PKG AS
            FUNCTION sello(p_anterior IN VARCHAR2, p_evento IN CLOB) RETURN VARCHAR2 IS
            BEGIN
                RETURN LOWER(RAWTOHEX(DBMS_CRYPTO.HASH(
                    TO_CLOB(p_anterior) || TO_CLOB('|') || p_evento, DBMS_CRYPTO.HASH_SH256)));
            END;

            FUNCTION hash_evento(p_evento IN NUMBER) RETURN VARCHAR2 IS
                v_anterior VARCHAR2(64);
                v_json CLOB;
            BEGIN
                SELECT k."KDX_Hash_Anterior", JSON_OBJECT('ACT_Activo' VALUE k."ACT_Activo", 'CON_Consumible' VALUE k."CON_Consumible", 'KDX_Cantidad' VALUE k."KDX_Cantidad", 'KDX_Costo' VALUE k."KDX_Costo", 'KDX_Destino_Activo' VALUE k."KDX_Destino_Activo", 'KDX_Destino_Area' VALUE k."KDX_Destino_Area", 'KDX_Destino_Persona' VALUE k."KDX_Destino_Persona", 'KDX_Destino_Sede' VALUE k."KDX_Destino_Sede", 'KDX_Detalle' VALUE k."KDX_Detalle" FORMAT JSON, 'KDX_Documento_Ref' VALUE k."KDX_Documento_Ref", 'KDX_Documento_Tipo' VALUE k."KDX_Documento_Tipo", 'KDX_Evento' VALUE k."KDX_Evento", 'KDX_Fecha' VALUE k."KDX_Fecha", 'KDX_Hash_Anterior' VALUE k."KDX_Hash_Anterior", 'KDX_Migrado' VALUE k."KDX_Migrado", 'KDX_Moneda' VALUE k."KDX_Moneda", 'KDX_Motivo' VALUE k."KDX_Motivo", 'KDX_Objeto' VALUE k."KDX_Objeto", 'KDX_Origen_Activo' VALUE k."KDX_Origen_Activo", 'KDX_Origen_Area' VALUE k."KDX_Origen_Area", 'KDX_Origen_Persona' VALUE k."KDX_Origen_Persona", 'KDX_Origen_Sede' VALUE k."KDX_Origen_Sede", 'KDX_Referencia' VALUE k."KDX_Referencia", 'KDX_Saldo' VALUE k."KDX_Saldo", 'KDX_Saldo_Valor' VALUE k."KDX_Saldo_Valor", 'KDX_Secuencia' VALUE k."KDX_Secuencia", 'KDX_Tipo' VALUE k."KDX_Tipo", 'LCL_Licencia_Clave' VALUE k."LCL_Licencia_Clave", 'LIC_Licencia' VALUE k."LIC_Licencia", 'SED_Sede' VALUE k."SED_Sede", 'USU_Usuario' VALUE k."USU_Usuario" ABSENT ON NULL RETURNING CLOB)
                  INTO v_anterior, v_json
                  FROM "INV_KARDEX" k WHERE k."KDX_Evento" = p_evento;
                RETURN sello(v_anterior, v_json);
            END;
        END INV_KARDEX_PKG;
